#!/bin/zsh
# Builds "English with Movies.app" into ./build (no Xcode needed).
# Usage: scripts/build-app.sh [--universal]
set -euo pipefail
cd "$(dirname "$0")/.."

APP="build/English with Movies.app"
# --universal builds for both Apple Silicon and Intel Macs (used for releases).
ARCHS=()
[[ "${1:-}" == "--universal" ]] && ARCHS=(--arch arm64 --arch x86_64)
swift build -c release --product EnglishWithMovies "${ARCHS[@]}"
BIN="$(swift build -c release --product EnglishWithMovies "${ARCHS[@]}" --show-bin-path)"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN/EnglishWithMovies" "$APP/Contents/MacOS/EnglishWithMovies"
# Icon generated by scripts/make-icon.swift
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
# Setup scripts for the sound (phoneme) analysis
cp -R Sources/EnglishWithMovies/Phonemes "$APP/Contents/Resources/Phonemes"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>English with Movies</string>
    <key>CFBundleDisplayName</key><string>English with Movies &amp; Music</string>
    <key>CFBundleIdentifier</key><string>com.titanlancsak.englishwithmovies</string>
    <key>CFBundleExecutable</key><string>EnglishWithMovies</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundleShortVersionString</key><string>1.1.0</string>
    <key>CFBundleVersion</key><string>2</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <key>NSHighResolutionCapable</key><true/>
    <key>NSMicrophoneUsageDescription</key><string>O microfone é usado para avaliar a sua pronúncia das falas.</string>
    <key>LSApplicationCategoryType</key><string>public.app-category.education</string>
    <key>CFBundleDocumentTypes</key>
    <array>
        <dict>
            <key>CFBundleTypeName</key><string>Media</string>
            <key>CFBundleTypeRole</key><string>Viewer</string>
            <key>LSHandlerRank</key><string>Alternate</string>
            <key>LSItemContentTypes</key>
            <array>
                <string>public.movie</string>
                <string>public.audio</string>
                <string>org.matroska.mkv</string>
            </array>
        </dict>
    </array>
</dict>
</plist>
PLIST

codesign --force --sign - "$APP" >/dev/null
touch "$APP"  # makes Finder/Dock pick up the new icon
echo "Pronto: $APP"
