"""Writes the list of common English words used to highlight uncommon words in the subtitles.

Source: wordfreq (https://github.com/rspeer/wordfreq), whose English data includes film and TV
subtitles (OpenSubtitles). Data license: CC BY-SA 4.0.

Usage: python scripts/make-common-words.py   (needs `pip install wordfreq`)
Writes data/common-words.txt and the copies compiled into the apps:
Sources/LinguaCore/CommonWordsData.swift and app-flutter/lib/core/common_words_data.dart.
"""
import pathlib
import re

import wordfreq

COUNT = 5000
ROOT = pathlib.Path(__file__).resolve().parent.parent

words = [w for w in wordfreq.top_n_list("en", 12000) if re.fullmatch(r"[a-z]+(?:'[a-z]+)?", w)][:COUNT]
text = " ".join(words)
header = f"The {COUNT} most common English words (wordfreq, CC BY-SA 4.0). Generated by scripts/make-common-words.py."

(ROOT / "data/common-words.txt").write_text("\n".join(words) + "\n", encoding="utf-8")
(ROOT / "Sources/LinguaCore/CommonWordsData.swift").write_text(
    f"// {header}\n\nextension CommonWords {{\n    static let data = \"{text}\"\n}}\n", encoding="utf-8")
(ROOT / "app-flutter/lib/core/common_words_data.dart").write_text(
    f"// {header}\n\nconst commonWordsData = \"{text}\";\n", encoding="utf-8")
print(f"{len(words)} words")
